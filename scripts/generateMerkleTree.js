const { buildPoseidon } = require("circomlibjs");
const fs = require("fs");
const path = require("path");

/**
 * Simple Merkle Tree implementation using Poseidon hash
 * Compatible with circomlib's MerkleTreeInclusionProof
 */
class PoseidonMerkleTree {
    constructor(depth, poseidon) {
        this.depth = depth;
        this.poseidon = poseidon;
        this.leaves = [];
        this.zeroValue = BigInt(0);
        this.maxLeaves = 2 ** depth;
    }

    /**
     * Insert a leaf into the tree
     */
    insert(leaf) {
        if (this.leaves.length >= this.maxLeaves) {
            throw new Error("Tree is full");
        }
        this.leaves.push(leaf);
    }

    /**
     * Hash two values using Poseidon
     */
    hash(left, right) {
        const result = this.poseidon([left, right]);
        // Convert to BigInt if it's a field element
        return BigInt(this.poseidon.F.toString(result));
    }

    /**
     * Get the root of the tree
     */
    getRoot() {
        if (this.leaves.length === 0) {
            // Return zero root for empty tree
            let zeroRoot = this.zeroValue;
            for (let i = 0; i < this.depth; i++) {
                zeroRoot = this.hash(zeroRoot, zeroRoot);
            }
            return zeroRoot;
        }
        
        // Build tree from bottom up
        let currentLevel = [...this.leaves];
        const maxLeavesAtLevel = 2 ** this.depth;
        
        // Pad to max leaves
        while (currentLevel.length < maxLeavesAtLevel) {
            currentLevel.push(this.zeroValue);
        }
        
        // Build tree level by level
        for (let level = 0; level < this.depth; level++) {
            const nextLevel = [];
            for (let i = 0; i < currentLevel.length; i += 2) {
                const left = currentLevel[i];
                const right = currentLevel[i + 1];
                nextLevel.push(this.hash(left, right));
            }
            currentLevel = nextLevel;
        }
        
        return currentLevel[0];
    }

    /**
     * Generate Merkle proof for a leaf at the given index
     * Returns { pathElements, pathIndices }
     * pathIndices: 0 = left, 1 = right
     */
    genMerklePath(leafIndex) {
        const pathElements = [];
        const pathIndices = [];
        
        // Build tree levels
        let currentLevel = [...this.leaves];
        const maxLeavesAtLevel = 2 ** this.depth;
        
        // Pad to max leaves
        while (currentLevel.length < maxLeavesAtLevel) {
            currentLevel.push(this.zeroValue);
        }
        
        let currentIndex = leafIndex;
        
        // Traverse up the tree
        for (let level = 0; level < this.depth; level++) {
            const siblingIndex = currentIndex % 2 === 0 ? currentIndex + 1 : currentIndex - 1;
            pathElements.push(currentLevel[siblingIndex].toString());
            pathIndices.push((currentIndex % 2).toString());
            
            // Build next level
            const nextLevel = [];
            for (let i = 0; i < currentLevel.length; i += 2) {
                const left = currentLevel[i];
                const right = currentLevel[i + 1];
                nextLevel.push(this.hash(left, right));
            }
            currentLevel = nextLevel;
            currentIndex = Math.floor(currentIndex / 2);
        }
        
        return { pathElements, pathIndices };
    }
}

async function generateMerkleTree() {
    const TREE_DEPTH = 7;
    
    // Initialize Poseidon hash function
    const poseidon = await buildPoseidon();
    
    // Generate mock identity and action-nullifier secrets.
    // In production, these would be randomly generated by the user
    const identitySecret = BigInt("1234567890123456789012345678901234567890123456789012345678901234");
    const identityNullifierSecret = BigInt("9876543210987654321098765432109876543210987654321098765432109876");
    
    console.log("Generating Merkle Tree with Poseidon hash...");
    console.log(`Tree Depth: ${TREE_DEPTH}`);
    console.log(`Identity Secret: ${identitySecret.toString()}`);
    console.log(`Identity Nullifier Secret: ${identityNullifierSecret.toString()}`);
    
    // Step 1: Compute the canonical identity leaf: Poseidon(identitySecret).
    const commitmentResult = poseidon([identitySecret]);
    const commitment = BigInt(poseidon.F.toString(commitmentResult));
    console.log(`\nCommitment (Poseidon(identitySecret)): ${commitment.toString()}`);
    
    // Step 2: Create Merkle Tree with Poseidon hash
    const tree = new PoseidonMerkleTree(TREE_DEPTH, poseidon);
    
    // Step 3: Insert the commitment as a leaf at index 0
    const leafIndex = 0;
    tree.insert(commitment);
    
    // Add a few more dummy leaves to make the tree more realistic
    for (let i = 1; i < 5; i++) {
        const dummySecret = BigInt(i * 1000);
        const dummyCommitmentResult = poseidon([dummySecret]);
        const dummyCommitment = BigInt(poseidon.F.toString(dummyCommitmentResult));
        tree.insert(dummyCommitment);
    }
    
    // Step 4: Generate Merkle proof for our commitment
    const proof = tree.genMerklePath(leafIndex);
    
    // Extract path elements and indices (already strings from genMerklePath)
    const pathElements = proof.pathElements;
    const pathIndices = proof.pathIndices;
    
    // Get the root
    const root = tree.getRoot().toString();
    
    console.log(`\nMerkle Root: ${root}`);
    console.log(`Leaf Index: ${leafIndex}`);
    console.log(`Path Elements (${pathElements.length}): [${pathElements.join(", ")}]`);
    console.log(`Path Indices (${pathIndices.length}): [${pathIndices.join(", ")}]`);
    
    // Step 5: Generate a sample actionId (e.g., a request ID)
    const actionId = BigInt("1234567890123456789012345678901234567890123456789012345678901234");
    
    // Step 6: Compute action nullifier (Poseidon(identityNullifierSecret, actionId)).
    const nullifierHashResult = poseidon([identityNullifierSecret, actionId]);
    const nullifierHash = BigInt(poseidon.F.toString(nullifierHashResult));
    
    console.log(`\nAction ID: ${actionId.toString()}`);
    console.log(`Nullifier Hash: ${nullifierHash.toString()}`);
    
    // Step 7: Create input.json for the circuit
    const input = {
        identitySecret: identitySecret.toString(),
        identityNullifierSecret: identityNullifierSecret.toString(),
        pathElements: pathElements,
        pathIndices: pathIndices,
        root: root,
        actionId: actionId.toString()
    };
    
    // Write input.json to the circuits directory
    const inputPath = path.join(__dirname, "..", "circuits", "input.json");
    fs.writeFileSync(inputPath, JSON.stringify(input, null, 2));
    
    console.log(`\n✅ Successfully generated input.json at: ${inputPath}`);
    console.log("\nInput structure:");
    console.log(JSON.stringify(input, null, 2));
    
    return {
        root,
        actionId: actionId.toString(),
        nullifierHash: nullifierHash.toString(),
        commitment: commitment.toString(),
        leafIndex
    };
}

// Run the script
generateMerkleTree()
    .then((result) => {
        console.log("\n✅ Merkle tree generation completed successfully!");
        console.log("\nSummary:");
        console.log(`  Root: ${result.root}`);
        console.log(`  Action ID: ${result.actionId}`);
        console.log(`  Nullifier Hash: ${result.nullifierHash}`);
        console.log(`  Commitment: ${result.commitment}`);
        console.log(`  Leaf Index: ${result.leafIndex}`);
    })
    .catch((error) => {
        console.error("❌ Error generating Merkle tree:", error);
        process.exit(1);
    });
