const { buildPoseidon } = require("circomlibjs");
const { IncrementalMerkleTree } = require("@zk-kit/incremental-merkle-tree");
const fs = require("fs");
const path = require("path");

async function generateMerkleTree() {
    const TREE_DEPTH = 5;
    
    // Initialize Poseidon hash function
    const poseidon = await buildPoseidon();
    
    // Create hash function compatible with zk-kit IncrementalMerkleTree
    const hash = (inputs) => {
        return BigInt(
            poseidon.F.toObject(
                poseidon(
                    inputs.map(x => BigInt(x))
                )
            )
        );
    };
    
    // Generate mock identity secret and nullifier
    // In production, these would be randomly generated by the user
    const identitySecret = BigInt("1234567890123456789012345678901234567890123456789012345678901234");
    const identityNullifier = BigInt("9876543210987654321098765432109876543210987654321098765432109876");
    
    console.log("Generating Merkle Tree with Poseidon hash using @zk-kit/incremental-merkle-tree...");
    console.log(`Tree Depth: ${TREE_DEPTH}`);
    console.log(`Identity Secret: ${identitySecret.toString()}`);
    console.log(`Identity Nullifier: ${identityNullifier.toString()}`);
    
    // Step 1: Compute the commitment (Poseidon hash of secret and nullifier)
    const commitment = hash([identitySecret, identityNullifier]);
    console.log(`\nCommitment (Poseidon(secret, nullifier)): ${commitment.toString()}`);
    
    // Step 2: Create Merkle Tree with zk-kit IncrementalMerkleTree
    const tree = new IncrementalMerkleTree(
        hash,
        TREE_DEPTH,
        BigInt(0),
        2
    );
    
    // Step 3: Insert the commitment as a leaf at index 0
    const leafIndex = 0;
    tree.insert(commitment);
    
    // Add a few more dummy leaves to make the tree more realistic
    for (let i = 1; i < 5; i++) {
        const dummySecret = BigInt(i * 1000);
        const dummyNullifier = BigInt(i * 2000);
        const dummyCommitment = hash([dummySecret, dummyNullifier]);
        tree.insert(dummyCommitment);
    }
    
    // Step 4: Generate Merkle proof for our commitment
    const proof = tree.createProof(leafIndex);
    
    // Extract path elements and indices
    const pathElements = proof.siblings.map(s => s.toString());
    const pathIndices = proof.pathIndices.map(i => i.toString());
    
    // Get the root
    const root = tree.root.toString();
    
    console.log(`\nMerkle Root: ${root}`);
    console.log(`Leaf Index: ${leafIndex}`);
    console.log(`Path Elements (${pathElements.length}): [${pathElements.join(", ")}]`);
    console.log(`Path Indices (${pathIndices.length}): [${pathIndices.join(", ")}]`);
    
    // Step 5: Generate a sample actionId (e.g., a request ID)
    const actionId = BigInt("1234567890123456789012345678901234567890123456789012345678901234");
    
    // Step 6: Compute nullifier hash (Poseidon(nullifier, actionId))
    const nullifierHash = hash([identityNullifier, actionId]);
    
    console.log(`\nAction ID: ${actionId.toString()}`);
    console.log(`Nullifier Hash: ${nullifierHash.toString()}`);
    
    // Step 7: Create input.json for the circuit
    const input = {
        identitySecret: identitySecret.toString(),
        identityNullifier: identityNullifier.toString(),
        pathElements: pathElements,
        pathIndices: pathIndices,
        root: root,
        actionId: actionId.toString()
    };
    
    // Write input.json to the circuits directory
    const inputPath = path.join(__dirname, "..", "circuits", "input.json");
    fs.writeFileSync(inputPath, JSON.stringify(input, null, 2));
    
    console.log(`\n✅ Successfully generated input.json at: ${inputPath}`);
    console.log("\nInput structure:");
    console.log(JSON.stringify(input, null, 2));
    
    return {
        root,
        actionId: actionId.toString(),
        nullifierHash: nullifierHash.toString(),
        commitment: commitment.toString(),
        leafIndex
    };
}

// Run the script
generateMerkleTree()
    .then((result) => {
        console.log("\n✅ Merkle tree generation completed successfully!");
        console.log("\nSummary:");
        console.log(`  Root: ${result.root}`);
        console.log(`  Action ID: ${result.actionId}`);
        console.log(`  Nullifier Hash: ${result.nullifierHash}`);
        console.log(`  Commitment: ${result.commitment}`);
        console.log(`  Leaf Index: ${result.leafIndex}`);
    })
    .catch((error) => {
        console.error("❌ Error generating Merkle tree:", error);
        process.exit(1);
    });

